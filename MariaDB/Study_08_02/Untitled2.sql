<제약조건(Constraint)>

테이블 컬럼에 '원치않는 데이터가 입력/변경/삭제되는 것을 방지'하기 위해
테이블 생성(create) or 변경(alter)시 설정하는 조건

제약조건은 table에 걸림 -> table삭제하면 제약조건도 삭제
제약조건만 삭제 가능
참고)제약조건명(Constraint 이름)을 개발자가 직접 부여하면,
	추후 해당 Constraint 관리가 용이하다
