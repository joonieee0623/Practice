[종류]

 (1) primary key(기본키 == 식별키 == 주키)
	- 하나의 Row(행) 데이터를 특정하는 키
	- 하나의 테이블에 오직 '하나'만 존재 가능(0 or 1)
	- 제약조건 이름과 같은 인덱스 객체가 자동으로 생성되어 부여됨
	- MariaDB에서는 개발자가 이름을 부여할 수 없음
	- 부여된 컬럼에 NULL 입력될 수 없음

 (2) foreign key(참조키(부모) == 외래키)
	- 부모테이블의 'PK 또는 UQ' 제약조건이 걸려있는 컬럼만 참조
	- 여러 개 가능

 (3) unique key(유일키)
	- PK가 아니더라도 컬럼의 모든 값이 '유일' 해야 하는 경우에 사용되는 키
	 (즉, 중복데이터를 허용하지 않는 컬럼에 부여)
	- PK와 차이점
	 여러개 가능
	 부여된 컬럼에 NULL 입력될 수 있음
	
 (4) check 
	- 조건에 맞는 데이터만 입력되도록 부여한 제약조건
	--조건? 
	 데이터의 범위
	 특정 패턴의 숫자
	 문자값 설정
	 등등 다양함

 (5) not null
	- null 이 입력되어서는 안되는 컬럼에 부여하는 제약조건
	 ('컬럼레벨' 에서만 부여 가능)

