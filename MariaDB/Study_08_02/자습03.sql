Constraint (제약조건)

**문제 1.
PRIMARY KEY 제약조건의 두 가지 특징을 쓰시오.
① NULL 값을 가질 수 없다 (NOT NULL) 
② 값이 중복될 수 없다 (UNIQUE)
PRIMARY KEY는 그 행을 대표하는 유일한 값이어야 하므로,
"비어있으면 안 되고" + "겹치면 안 되는" 두 규칙을 동시에 갖고 있어요. 
한 테이블에 딱 1개만 지정할 수 있어요.

**문제 2.
`이메일` 컬럼에 값이 중복되지 않도록 하되, PRIMARY KEY로는 쓰고 싶지 않다. 어떤 제약조건을 써야 하는가?
UNIQUE
`UNIQUE`도 중복은 막지만, PRIMARY KEY와 달리 NULL 값은 여러 번 허용돼요.
(NULL끼리는 "같다"고 비교하지 않기 때문)
그래서 필수값은 아니지만 겹치면 안 되는 이메일 같은 컬럼에 잘 어울려요.

**문제 3.
다음 테이블 정의에서 잘못된 부분을 찾아 고치시오.
```sql
CREATE TABLE 학생 (
    학번 VARCHAR(10) PRIMARY KEY,
    나이 INT CHECK (나이 > -5)
);
```
create table 학생(
	학번 varchar(10) primary key,
	나이 int check (나이 >= 0)
);
문법 자체는 틀리지 않았지만,나이가 -5보다 크기만 하면 되므로 -1, -2 같은 음수도 허용돼버려요.
나이는 보통 0 이상이어야 하므로 `나이 >= 0`으로 고치는 게 논리적으로 맞아요.
(CHECK 제약조건은 "문법 오류"보다 "조건이 실제 의미에 맞는지"를 확인하는 문제로 자주 나와요)

**문제 4.
`성적` 테이블의 `학번`이, 반드시 `학생` 테이블에 이미 존재하는 학번이어야 한다는 규칙을 세우고 싶다. 어떤 제약조건을 쓰는가? SQL도 함께 작성하시오.
create table 성적
 학번 varchart(10),
 점수 int,
 foreign key (학번) references 학생(학번)
);

`FOREIGN KEY (내 컬럼) REFERENCES 부모테이블(부모컬럼)` 문법으로,
다른 테이블(부모)에 실제 존재하는 값만 넣을 수 있게 제한해요.
이렇게 하면 존재하지도 않는 학번의 성적 데이터가 들어오는 걸 막을 수 있어요(참조 무결성).

*문제 5.
부모 테이블(학생)의 행이 삭제될 때, 자식 테이블(성적)의 관련 행도 자동으로 함께 삭제되게 하려면 FOREIGN KEY 뒤에 어떤 옵션을 붙여야 하는가?
ON DELETE CASCADE
예를 들어 `FOREIGN KEY (학번) REFERENCES 학생(학번) ON DELETE CASCADE`로 설정하면,
학생 테이블에서 특정 학번이 삭제될 때 성적 테이블에서도 그 학번과 관련된 행이 자동으로 같이 삭제돼요.
(이 옵션이 없으면 자식 데이터가 남아있는 부모 행은 삭제 자체가 거부돼요)

*문제 6.
`가입일` 컬럼에 값을 넣지 않으면 자동으로 오늘 날짜가 들어가도록 하고 싶다. SQL을 작성하시오.
가입일 date default (current_date);

**문제 7.
`이름` 컬럼에 값이 반드시 있어야 하고 절대 비워둘 수 없게 하려면 어떤 제약조건을 쓰는가?
NOT NULL
`이름 VARCHAR(20) NOT NULL`처럼 쓰면,
이 컬럼에 값을 넣지 않고 INSERT하려고 하면 에러가 발생해요.

**문제 8.
UNIQUE 제약조건과 PRIMARY KEY 제약조건의 공통점과 차이점을 각각 한 가지씩 쓰시오.
공통점: 둘 다 값의 **중복을 허용하지 않는다**.
차이점: PRIMARY KEY 는 **NULL을 허용하지 않고 테이블당 1개만** 지정할 수 있지만,
UNIQUE 는 **NULL을 여러 번 허용**하고 **한 테이블에 여러 개** 지정할 수 있다.

**문제 9.**
