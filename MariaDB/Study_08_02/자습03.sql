① 값이 비어있으면 안 된다 NOT NULL
② 값은 항상 다른 테이블에 존재해야 한다 FOREIGN KEY
③ 성별은 '남' 또는 '여'만 들어올 수 있다 CHECK
④ 값이 중복되면 안 된다 UNIQUE
"특정 조건식을 만족해야만 입력 가능"한 규칙(예: 특정 값들 중 하나여야 함, 범위 안이어야 함)

**문제 10.**
다음 테이블 정의를 보고, 회원 테이블 하나에 걸려있는 제약조건을 모두 찾아 이름과 역할을 설명하시오.
```sql
CREATE TABLE 회원 (
    ID VARCHAR(10) PRIMARY KEY,
    이름 VARCHAR(20) NOT NULL,
    이메일 VARCHAR(30) UNIQUE,
    나이 INT CHECK (나이 >= 0),
    가입일 DATE DEFAULT (CURRENT_DATE)
);
```
- `PRIMARY KEY` (ID) — ID는 중복 불가 + NULL 불가, 회원을 대표하는 값
- `NOT NULL` (이름) — 이름은 반드시 입력해야 함
- `UNIQUE` (이메일) — 이메일은 서로 겹칠 수 없음 (단, NULL은 여러 번 가능)
- `CHECK` (나이) — 나이는 0 이상인 값만 허용
- `DEFAULT` (가입일) — 값을 안 넣으면 오늘 날짜가 자동 입력